"""Small LAN API for the PathSnap evaluator dashboard.

Serves saved student-test evaluation results and maps from this project. It
does not retrain or run the classifier; model scores and HMM predictions are
generated by run_hmm.py and loaded from hmm_outputs/.
"""

from __future__ import annotations

import csv
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse

ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = ROOT / "hmm_outputs"
METRICS_FILE = OUTPUTS / "route_continuity.csv"

app = FastAPI(title="PathSnap Evaluation API", version="1.0.0")
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=False,
    allow_methods=["GET"],
    allow_headers=["*"],
)


def load_metrics() -> dict[str, dict[str, str]]:
    if not METRICS_FILE.is_file():
        raise HTTPException(status_code=503, detail="Run run_hmm.py to generate evaluation results.")
    with METRICS_FILE.open(newline="", encoding="utf-8") as stream:
        return {row["trip_id"].zfill(8): row for row in csv.DictReader(stream)}


@app.get("/api/health")
def health():
    return {"status": "ok", "results_available": METRICS_FILE.is_file()}


@app.get("/api/trips")
def trips():
    """Return trip IDs and small summary metrics for the selector."""
    rows = load_metrics()
    return [
        {
            "trip_id": trip_id,
            "gps_observations": int(row.get("gps_observations") or 0),
            "classifier_macro_f1": row.get("classifier_macro_f1"),
            "hmm_macro_f1": row.get("hmm_macro_f1"),
        }
        for trip_id, row in sorted(rows.items())
    ]


@app.get("/api/trips/{trip_id}")
def trip_metrics(trip_id: str):
    trip_id = trip_id.zfill(8)
    row = load_metrics().get(trip_id)
    if row is None:
        raise HTTPException(status_code=404, detail="Unknown evaluation trip.")
    return row


@app.get("/api/trips/{trip_id}/map")
def trip_map(trip_id: str):
    # Restrict IDs to digits before constructing a path.
    if not trip_id.isdigit():
        raise HTTPException(status_code=404, detail="Unknown evaluation trip.")
    path = OUTPUTS / f"{trip_id.zfill(8)}_prediction_map.html"
    if not path.is_file():
        raise HTTPException(status_code=404, detail="No saved map exists for this trip.")
    return FileResponse(path, media_type="text/html")
